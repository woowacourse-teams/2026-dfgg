package dfgg.domain.match;

/**
 * 구매한 아이템의 용도를 구분하는 서비스 분류다. 구매·판매·취소 같은 행동 타입과 다르다.
 * 공식 아이템 tier를 그대로 옮긴 값이 아니며, 해당 패치의 카탈로그와 분류 정책으로 결정한다.
 *
 * <p>예를 들어 첫 구매라도 롱소드는 COMPONENT다. 구매 시점이나 순번으로 STARTER를 판단하지 않는다.
 * 신발이 완성 아이템이더라도 BOOTS로 구분할 수 있도록 분류 정책에서 우선순위를 정해야 한다.
 * 이 enum 자체는 아이템을 자동 분류하거나 Core 추천 대상 여부를 결정하지 않는다.
 */
public enum ItemPurchaseType {

    /** 시작 아이템 용도로 지정한 아이템. 예: 도란 계열. 단순히 첫 번째로 구매한 아이템을 뜻하지 않는다. */
    STARTER,

    /** 상위 아이템을 만드는 기본 재료와 중간 조합 아이템. 예: 롱소드, 곡괭이. */
    COMPONENT,

    /** 서비스 정책에서 Core로 지정한 완성 아이템. 예: 칠흑의 양날 도끼. */
    CORE,

    /** 기본 신발과 업그레이드 신발. 완성 여부와 별개로 신발 계열을 구분한다. */
    BOOTS,

    /** 사용 시 소모되는 아이템 용도로 지정한 아이템. 예: 체력 물약, 제어 와드. */
    CONSUMABLE,

    /** 위 분류에 해당하지 않는 것으로 확인한 아이템. 예: 장신구. 분류 누락·미확인 아이템의 기본값은 아니다. */
    OTHER
}
