-- 대회 경기의 선수 한 명의 픽. Leaguepedia ScoreboardPlayers 한 행에서 온다. 스키마만 만든다.
CREATE TABLE pro_picks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tournament_id BIGINT NOT NULL REFERENCES pro_tournaments (id),
    player_id BIGINT NOT NULL REFERENCES pro_players (id),
    -- Leaguepedia GameId
    source_game_id VARCHAR(255) NOT NULL,
    played_at TIMESTAMPTZ NOT NULL,
    team VARCHAR(255) NOT NULL,
    -- Leaguepedia Side 1·2를 변환해서 넣는다.
    side VARCHAR(8) NOT NULL CHECK (side IN ('BLUE', 'RED')),
    position VARCHAR(16) NOT NULL CHECK (position IN ('TOP', 'JUNGLE', 'MID', 'BOTTOM', 'SUPPORT')),
    champion_id BIGINT NOT NULL REFERENCES champions (champion_id),
    win BOOLEAN NOT NULL,
    -- 같은 경기를 다시 수집해도 중복되지 않는다.
    CONSTRAINT uk_pro_picks_game_player UNIQUE (source_game_id, player_id)
);

-- 최근 대회 판정(played_at이 가장 늦은 픽)
CREATE INDEX idx_pro_picks_played_at ON pro_picks (played_at DESC);
-- (대회, 포지션) 픽 조회
CREATE INDEX idx_pro_picks_tournament_position ON pro_picks (tournament_id, position, played_at DESC);
