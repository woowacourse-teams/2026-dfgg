-- 상대 픽 분석의 라인 분포. 현재 패치에서 챔피언이 각 포지션으로 나온 수를 담는다.
-- 비율은 조회할 때 챔피언 합계로 나눠 구한다. 이전 패치 행은 남기고 patch로 거른다.
CREATE TABLE champion_position_stats (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patch VARCHAR(16) NOT NULL,
    champion_id INTEGER NOT NULL,
    position VARCHAR(16) NOT NULL CHECK (position IN ('TOP', 'JUNGLE', 'MID', 'BOTTOM', 'SUPPORT')),
    games INTEGER NOT NULL CHECK (games > 0),
    CONSTRAINT uk_champion_position_stats UNIQUE (patch, champion_id, position)
);
