-- 대회 픽의 대회. Leaguepedia Tournaments에서 온다. 스키마만 만든다.
CREATE TABLE pro_tournaments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Leaguepedia OverviewPage (예: 2026 Season World Championship/Main Event). 수집 때 같은 대회를 찾는 키다.
    overview_page VARCHAR(255) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    league VARCHAR(255) NOT NULL,
    region VARCHAR(64),
    -- 진행 중인 대회는 종료일이 비어 있을 수 있다.
    start_date DATE,
    end_date DATE,
    CONSTRAINT ck_pro_tournaments_dates CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date)
);
