-- 대회 픽의 선수. Leaguepedia Players·PlayerImages에서 온다. 스키마만 만든다.
CREATE TABLE pro_players (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Leaguepedia 페이지 이름 (예: Kratos (Ngô Đức Khánh)). 동명이인을 가른다.
    leaguepedia_page VARCHAR(255) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    -- 현재 소속. 경기 당시 소속은 pro_picks.team에 있다.
    team VARCHAR(255),
    -- 가장 최근 대회 프로필 사진 URL. 없을 수 있다.
    image_url TEXT,
    updated_at TIMESTAMPTZ NOT NULL
);
