-- 참가자별 룬 페이지를 Raw Match JSON에서 꺼내 저장한다. 기존 참가자 테이블은 그대로 둔다.
CREATE TABLE normalized_match_participant_runes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id VARCHAR(32) NOT NULL,
    participant_id INTEGER NOT NULL CHECK (participant_id > 0),
    -- 룬 통계를 이 테이블만으로 집계하도록 참가자 정보를 함께 둔다.
    -- 맞라인 상대는 같은 match_id·position에서 team_id가 다른 행이다.
    patch VARCHAR(16) NOT NULL,
    champion_id INTEGER NOT NULL,
    team_id INTEGER NOT NULL,
    position VARCHAR(32),
    win BOOLEAN NOT NULL,
    -- 룬 페이지는 모양이 고정이므로 룬마다 행을 나누지 않고 선택 순서대로 칸에 펼친다.
    -- 주 계열의 첫 번째 룬이 핵심 룬이다.
    primary_style_id INTEGER NOT NULL,
    keystone_id INTEGER NOT NULL,
    primary_perk1_id INTEGER NOT NULL,
    primary_perk2_id INTEGER NOT NULL,
    primary_perk3_id INTEGER NOT NULL,
    sub_style_id INTEGER NOT NULL,
    sub_perk1_id INTEGER NOT NULL,
    sub_perk2_id INTEGER NOT NULL,
    stat_offense_id INTEGER NOT NULL,
    stat_flex_id INTEGER NOT NULL,
    stat_defense_id INTEGER NOT NULL,
    CONSTRAINT uk_participant_rune UNIQUE (match_id, participant_id),
    CONSTRAINT ck_participant_rune_styles CHECK (primary_style_id <> sub_style_id)
);

-- 룬 추천이 내 챔피언·포지션과 최근 패치로 조회한다.
CREATE INDEX idx_participant_rune_champion_position_patch
    ON normalized_match_participant_runes (champion_id, position, patch);
