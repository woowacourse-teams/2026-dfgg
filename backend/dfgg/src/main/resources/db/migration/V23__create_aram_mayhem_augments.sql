-- 증강 칼바람(큐 2400)의 패치별 증강 카탈로그. 패치마다 이름과 등급이 바뀔 수 있어 패치별로 저장한다.
-- 이미지는 S3의 dfgg/images/{패치}/augments/{augment_id}.png에 따로 저장한다.
CREATE TABLE aram_mayhem_augments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patch VARCHAR(16) NOT NULL,
    augment_id INTEGER NOT NULL CHECK (augment_id > 0),
    -- 챔피언·아이템과 같은 {"ko-KR": ..., "en-US": ...} 형식
    name JSONB NOT NULL,
    rarity VARCHAR(16) NOT NULL CHECK (rarity IN ('SILVER', 'GOLD', 'PRISMATIC')),
    CONSTRAINT uk_aram_mayhem_augment UNIQUE (patch, augment_id)
);

-- 외부 데이터의 챔피언별 증강 픽률. Riot 정책상 증강 승률은 표시할 수 없어 저장하지 않는다.
-- 패치를 다시 수집할 때 증강을 지우면 그 패치의 픽률도 함께 지워진다.
CREATE TABLE aram_mayhem_champion_augments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patch VARCHAR(16) NOT NULL,
    champion_id INTEGER NOT NULL,
    augment_id INTEGER NOT NULL,
    games BIGINT NOT NULL CHECK (games >= 0),
    -- 그 챔피언 판 중 게임 종료 시 이 증강을 가진 비율(%). 한 판에 약 4개를 가져서 챔피언별 합이 약 400%다.
    pick_rate DOUBLE PRECISION NOT NULL CHECK (pick_rate BETWEEN 0 AND 100),
    CONSTRAINT uk_aram_mayhem_champion_augment UNIQUE (patch, champion_id, augment_id),
    CONSTRAINT fk_aram_mayhem_champion_augment_augment FOREIGN KEY (patch, augment_id)
        REFERENCES aram_mayhem_augments (patch, augment_id) ON DELETE CASCADE
);
