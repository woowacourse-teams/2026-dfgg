-- 상대 픽 분석의 내 라인 카운터. (적 챔피언, 라인)마다 순서 있는 카운터 최대 7개를 사용자가 SQL로 직접 넣는다.
-- 통계로 계산하지 않고 패치와 무관하다. 7개를 두는 이유는 아군·적·밴으로 빠져도 5개를 채우기 위해서다.
-- 이 마이그레이션은 스키마만 만든다. 데이터 INSERT를 넣지 않는다.
CREATE TABLE champion_counters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enemy_champion_id INTEGER NOT NULL,
    -- 수집 데이터의 MIDDLE·UTILITY가 아니라 서비스 표기(MID·SUPPORT)만 받는다.
    position VARCHAR(16) NOT NULL CHECK (position IN ('TOP', 'JUNGLE', 'MID', 'BOTTOM', 'SUPPORT')),
    counter_champion_id INTEGER NOT NULL,
    rank INTEGER NOT NULL CHECK (rank BETWEEN 1 AND 7),
    -- 자기 자신은 카운터가 아니다. 입력 실수로 들어오면 응답에서 픽·적 제외로 조용히 사라져 찾기 어렵다.
    CONSTRAINT ck_champion_counters_not_self CHECK (counter_champion_id <> enemy_champion_id),
    CONSTRAINT uk_champion_counters_counter UNIQUE (enemy_champion_id, position, counter_champion_id),
    -- 조회 순서(enemy, position, rank)와 같아서 이 유니크 인덱스가 조회 인덱스를 겸한다.
    CONSTRAINT uk_champion_counters_rank UNIQUE (enemy_champion_id, position, rank)
);
